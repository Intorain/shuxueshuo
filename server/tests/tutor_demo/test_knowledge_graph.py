"""Published graph and resource boundaries after the formal stage-4 replacement."""

import json
import re
import subprocess
from pathlib import Path

from .test_local_practice import ROOT

DATA = ROOT / 'site/data/knowledge-next'
NODES = {p.stem: json.loads(p.read_text()) for p in (DATA / 'nodes').glob('*.json')}
CATALOG = json.loads((DATA / 'catalog.json').read_text())
EXPLAIN = ROOT / 'site/assets/explain'


def test_public_graph_preserves_explicit_types_and_subtypes():
    graph = json.loads((ROOT / 'site/knowledge/graph.json').read_text())
    assert len(graph['nodes']) == len(NODES)
    assert {node['id'] for node in graph['nodes']} == set(NODES)
    assert len({node['kind'] for node in graph['nodes']}) == 8
    assert NODES['method-complete-square']['kind'] == 'skill'
    assert NODES['method-square-extremum']['kind'] == 'method'
    for edge in graph['edges']:
        assert edge['from'] in NODES and edge['to'] in NODES
        if NODES[edge['from']]['kind'] == 'chapter':
            assert NODES[edge['to']]['kind'] == 'section'
        if NODES[edge['from']]['kind'] == 'judgment_rule':
            assert NODES[edge['to']]['kind'] in {'method', 'skill'}


def test_all_current_pages_build_from_one_generator():
    result = subprocess.run(['node', 'tools/build-public-knowledge-graph.mjs', '--check'], cwd=ROOT, text=True, capture_output=True)
    assert result.returncode == 0, result.stderr
    for node in NODES:
        page = (ROOT / f'site/knowledge/{node}/index.html').read_text()
        assert 'Generated by tools/build-public-knowledge-graph.mjs' in page
        assert '/knowledge-next/assets/' not in page
    assert not (ROOT / 'tools/build-knowledge-pages.mjs').exists()
    assert not (ROOT / 'site/data/knowledge').exists()


def test_all_diagrams_use_reviewed_resource_paths_and_scopes():
    for resource in CATALOG['resources'].values():
        module = ROOT / 'site' / resource['module'].lstrip('/')
        assert module.is_file()
        source = module.read_text()
        assert 'export default {' in source
        assert 'tip.note' not in source or 'problemNote(tip.note)' in source
        assert resource['scope']
        for target in re.findall(r'data-explain-open="([a-z-]+)"', source):
            ref = CATALOG['resourceLinks'][target]
            assert ref.split('#')[0] in NODES
    shell = (EXPLAIN / 'explain.js').read_text()
    assert '/data/knowledge/' not in shell
    assert 'id.startsWith' not in shell


def test_published_teaching_catalog_has_no_private_assessment_answers():
    for path in (ROOT / 'site/knowledge/teaching').rglob('*.json'):
        value = path.read_text()
        for private_key in ('answer_spec', 'item_snapshot', '_lesson', 'required_evidence'):
            assert f'"{private_key}"' not in value, path
    drills = list((ROOT / 'server/shuxueshuo_server/learning/drills-next/sets').glob('*.json'))
    assert drills
    for path in drills:
        row = json.loads(path.read_text())
        assert row['node'] in NODES
    assert not (ROOT / 'server/shuxueshuo_server/learning/drills').exists()


def test_compatibility_links_keep_split_nodes_reviewable():
    mapping = json.loads((DATA / 'migration.json').read_text())
    for old, ref in mapping['legacyRefs'].items():
        node, _, entry = ref.partition('#')
        page = (ROOT / f'site/knowledge/{old}/index.html').read_text()
        assert f'/knowledge/{node}/#{entry}' in page
    split = (ROOT / 'site/knowledge/case-merge/index.html').read_text()
    for ref in next(row['targets'] for row in mapping['nodes'] if row['legacy'] == 'case-merge'):
        node, _, entry = ref.partition('#')
        assert f'/knowledge/{node}/#{entry}' in split
    assert 'compat-config' not in split
