"""Freeze only original problem paragraphs; render clean images with local KaTeX.

Site cases copy the paragraph from ``site/2``; authored cases (multi-part
problems absent from the site) keep ``problem.md`` as their source text. The
gold files are deliberately never generated by this tool. Use ``--check``
without a browser to verify the frozen input against its source.
"""

import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "server/tests/solver/fixtures/graph-guided-stage-one/quadratic-always"
SELECTOR = ".problem-card > p[data-math-text]"
SITE_CASES = tuple(f"q{number:02}" for number in range(1, 10))
AUTHORED_CASES = ("q10", "q11")
RENDER = {
    "renderer": "playwright-chromium-local-katex",
    "katex_version": "0.18.9",
    "viewport_width": 960,
    "device_scale_factor": 2,
    "font_family": "STHeiti",
    "font_size_px": 28,
    "line_height": 1.85,
    "padding_px": 40,
    "background": "#ffffff",
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def save(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


class ProblemParagraph(HTMLParser):
    """An exact direct-child selector, excluding the meaning panel and scripts."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.found, self.parts = [], [], None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        parent = self.stack[-1][1] if self.stack else {}
        if tag == "p" and "data-math-text" in attrs and "problem-card" in parent.get("class", "").split():
            self.parts = []
        if tag not in {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}:
            self.stack.append((tag, attrs))

    def handle_endtag(self, tag):
        if tag == "p" and self.parts is not None:
            self.found.append("".join(self.parts).strip())
            self.parts = None
        for index in range(len(self.stack) - 1, -1, -1):
            if self.stack[index][0] == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        if self.parts is not None:
            self.parts.append(data)


def problem_text(path):
    parser = ProblemParagraph()
    parser.feed(path.read_text(encoding="utf-8"))
    if len(parser.found) != 1:
        raise ValueError(f"{path}: expected one {SELECTOR}, got {len(parser.found)}")
    return parser.found[0]


RENDER_JS = r"""
const fs = require('fs');
const {chromium} = require(process.argv[2]);
const config = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
(async () => {
  const browser = await chromium.launch({headless: true, ...(config.executable ? {executablePath: config.executable} : {})});
  try {
    const page = await browser.newPage({viewport:{width:960,height:800},deviceScaleFactor:2});
    await page.route('**/*', route => route.request().url().startsWith('file:') ? route.continue() : route.abort());
    const css = fs.readFileSync(config.katex + '/katex.min.css','utf8').replace(/url\(([^)]+)\)/g, (_, p) => {
      const name = p.replace(/["']/g,'');
      const ext = name.split('.').pop();
      return `url(data:font/${ext};base64,${fs.readFileSync(config.katex+'/'+name).toString('base64')})`;
    });
    for (const item of config.items) {
      await page.setContent('<!doctype html><html lang="zh-CN"><meta charset="utf-8"><style>'+css+'\n*{box-sizing:border-box}html,body{margin:0;background:white}#problem{width:960px;padding:40px;font-family:STHeiti,sans-serif;font-size:28px;line-height:1.85;color:#111;overflow-wrap:break-word;white-space:pre-line}.katex{font-size:1.06em}</style><main id="problem"></main></html>');
      await page.addScriptTag({path:config.katex+'/katex.min.js'});
      await page.evaluate(text => {
        const root=document.querySelector('#problem');
        text.split(/(\$[^$]+\$)/g).filter(Boolean).forEach(part => {
          const span=document.createElement('span');
          if(part.startsWith('$')) katex.render(part.slice(1,-1),span,{throwOnError:true,strict:'error'});
          else span.textContent=part;
          root.append(span);
        });
      }, item.text);
      await page.evaluate(() => document.fonts.ready);
      await page.locator('#problem').screenshot({path:item.output});
    }
    fs.writeFileSync(config.result,JSON.stringify({browser_version:browser.version()}));
  } finally {await browser.close();}
})().catch(error=>{process.stderr.write(String(error.stack||error));process.exit(1)});
"""


def _text(case, folder):
    if case in AUTHORED_CASES:
        return (folder / "problem.md").read_text(encoding="utf-8").rstrip("\n")
    return problem_text(ROOT / f"site/2/{case}/index.html")


def _record(case, manifest):
    return {
        "case_id": case, "directory": case, "source": f"{case}/source.png",
        "source_kind": manifest["source_kind"], "source_sha256": manifest["source_sha256"],
        "problem": f"{case}/problem.md", "problem_sha256": manifest["problem_sha256"],
        "source_manifest": f"{case}/source-manifest.json",
        "notation_gold": f"{case}/notation.gold.json",
        "features_gold": f"{case}/features.gold.json",
        "acceptance": f"{case}/acceptance.json",
    }


def prepare(args):
    all_cases = (*SITE_CASES, *AUTHORED_CASES)
    cases = all_cases if args.check or not args.cases else tuple(args.cases)
    if not set(cases) <= set(all_cases):
        raise ValueError(f"unknown cases: {sorted(set(cases) - set(all_cases))}")
    items = []
    for case in cases:
        folder = args.output / case
        text = _text(case, folder)
        if args.check:
            manifest = json.loads((folder / "source-manifest.json").read_text())
            checks = {
                "problem_sha256": digest((text + "\n").encode()),
                "source_sha256": digest((folder / "source.png").read_bytes()),
                "render_sha256": digest(json.dumps(manifest["render_config"], sort_keys=True).encode()),
            }
            if case in SITE_CASES:
                checks["source_html_sha256"] = digest((ROOT / f"site/2/{case}/index.html").read_bytes())
            if (folder / "problem.md").read_text() != text + "\n":
                raise ValueError(f"{case}: frozen problem.md differs from original paragraph")
            for key, value in checks.items():
                if manifest.get(key) != value:
                    raise ValueError(f"{case}: {key} mismatch")
            continue
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "problem.md").write_text(text + "\n", encoding="utf-8")
        items.append({"text": text, "output": str(folder / "source.png")})
    if args.check:
        corpus = json.loads((args.output / "manifest.json").read_text())
        if [case["case_id"] for case in corpus["cases"]] != list(all_cases):
            raise ValueError("manifest.json case list differs from the corpus")
        print(f"Verified {len(all_cases)} frozen problem texts and image hashes.")
        return
    katex = ROOT / "site/assets/practice/vendor/katex-0.18.9"
    with tempfile.TemporaryDirectory(prefix="graph-stage-one-render-") as temporary:
        temp = Path(temporary)
        (temp / "render.cjs").write_text(RENDER_JS)
        save(temp / "config.json", {"items": items, "katex": str(katex), "executable": args.browser_executable, "result": str(temp / "result.json")})
        subprocess.run([args.node, str(temp / "render.cjs"), args.playwright_module, str(temp / "config.json")], check=True)
        renderer = json.loads((temp / "result.json").read_text())
    render_config = RENDER | renderer | {
        "katex_js_sha256": digest((katex / "katex.min.js").read_bytes()),
        "katex_css_sha256": digest((katex / "katex.min.css").read_bytes()),
        "render_script_sha256": digest(RENDER_JS.encode()),
    }
    font = Path("/System/Library/Fonts/STHeiti Light.ttc")
    if font.exists():
        render_config["font_file_sha256"] = digest(font.read_bytes())
    render_hash = digest(json.dumps(render_config, sort_keys=True).encode())
    for case in cases:
        folder = args.output / case
        manifest = {
            "schema_version": "graph-stage-one-source/v1",
            "case_id": case,
            "problem_sha256": digest((folder / "problem.md").read_bytes()),
            "source_sha256": digest((folder / "source.png").read_bytes()),
            "render_config": render_config,
            "render_sha256": render_hash,
        }
        if case in SITE_CASES:
            source = ROOT / f"site/2/{case}/index.html"
            manifest |= {
                "source_kind": "synthetic-rendered",
                "source_html": str(source.relative_to(ROOT)),
                "selector": SELECTOR,
                "source_html_sha256": digest(source.read_bytes()),
                "input_scope": "Only the direct original problem paragraph; no meaning panel, solutions, answers or scripts.",
            }
        else:
            manifest |= {
                "source_kind": "authored-rendered",
                "input_scope": "Authored multi-part problem text in problem.md; no solutions or answers.",
            }
        save(folder / "source-manifest.json", manifest)
    records = [
        _record(case, json.loads((args.output / case / "source-manifest.json").read_text()))
        for case in all_cases
    ]
    save(args.output / "manifest.json", {"schema_version": "graph-stage-one-corpus/v1", "source_kind": "synthetic-rendered", "cases": records})
    print(f"Prepared {len(cases)} clean source images in {args.output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=CORPUS)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cases", nargs="+", help="render only these cases; others keep their frozen images")
    parser.add_argument("--node", default="node")
    parser.add_argument("--playwright-module", default=os.environ.get("PLAYWRIGHT_MODULE", "playwright"))
    parser.add_argument("--browser-executable")
    prepare(parser.parse_args())
